# build_module.ps1 — concatenate the per-file SDK sources into a single AsposeCellsCloud.psm1.
#
# Why: PowerShell's `using module` only exposes classes defined DIRECTLY in the module's
# top-level AST. Classes dot-sourced from separate .ps1 files are loaded (Import-Module
# succeeds) but are NOT visible to a caller via `using module` / [Type] literals. To make the
# SDK's classes usable, every class definition must be concatenated inline into the .psm1.
#
# The per-file layout under Src/ remains the source of truth (one class per file, matching the
# Go SDK); this script produces the loadable aggregate from it.

param(
    [string]$Root = $PSScriptRoot
)

$ErrorActionPreference = 'Stop'

$src       = Join-Path $Root 'Src'
$modelsDir = Join-Path $src 'Models'
$reqDir    = Join-Path $src 'Requests'
$psm1      = Join-Path $Root 'AsposeCellsCloud.psm1'

$utf8 = New-Object System.Text.UTF8Encoding($false)
$sb   = [System.Text.StringBuilder]::new()

function Add-FileContent {
    param([string]$Path)
    $content = [System.IO.File]::ReadAllText($Path, $utf8).TrimEnd("`r", "`n")
    [void]$sb.AppendLine($content)
    [void]$sb.AppendLine('')
}

[void]$sb.AppendLine('# AsposeCellsCloud.psm1 — GENERATED by build_module.ps1. Do not edit by hand.')
[void]$sb.AppendLine('# All classes are concatenated inline so that `using module AsposeCellsCloud`')
[void]$sb.AppendLine('# exposes them to callers (dot-sourced classes are not exposed by `using module`).')
[void]$sb.AppendLine('')

# 1. JSON helper functions.
Add-FileContent (Join-Path $src 'AsposeJson.ps1')

# 2. Support types.
Add-FileContent (Join-Path $src 'SDKError.ps1')
Add-FileContent (Join-Path $src 'RichResponse.ps1')
Add-FileContent (Join-Path $src 'RequestOption.ps1')
Add-FileContent (Join-Path $src 'Configuration.ps1')

# 3. Model classes, in dependency order.
$orderFile = Join-Path $modelsDir '_load_order.txt'
if (Test-Path $orderFile) {
    $order = Get-Content -Path $orderFile | Where-Object { $_ -and -not $_.Trim().StartsWith('#') }
    foreach ($name in $order) {
        $f = if ($name -like '*.ps1') { $name } else { "$name.ps1" }
        Add-FileContent (Join-Path $modelsDir $f)
    }
}
else {
    Get-ChildItem -Path $modelsDir -Filter '*.ps1' -File | Sort-Object Name | ForEach-Object {
        Add-FileContent $_.FullName
    }
}

# 4. Request classes.
Get-ChildItem -Path $reqDir -Filter '*.ps1' -File | Sort-Object Name | ForEach-Object {
    Add-FileContent $_.FullName
}

# 5. Client.
Add-FileContent (Join-Path $src 'AsposeCellsCloudClient.ps1')

# 6. Exported functions.
[void]$sb.AppendLine("Export-ModuleMember -Function 'ConvertTo-AsposeJson', 'ConvertTo-AsposeHashtable', 'ConvertTo-AsposeQueryString'")

[System.IO.File]::WriteAllText($psm1, $sb.ToString(), $utf8)
Write-Host "Wrote $psm1"
